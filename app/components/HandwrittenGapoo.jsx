export function HandwrittenGapoo({
  className = '',
  color = '#fdfaf1',
  startDelay = 0.5,
  speedMultiplier = 1.0,
  interactive = true,
}) {
  const [key, setKey] = useState(0);
  const [isCompleted, setIsCompleted] = useState(false);
  const [uid] = useState(() => Math.random().toString(36).substring(2, 7));

  // Timing configuration: Crisp, continuous cursive handwriting cadence
  // Zero dead time: each letter starts precisely as the previous letter's stroke finishes
  const m = 1 / speedMultiplier;
  const letters = [
    {
      id: 'G',
      name: 'G',
      delay: startDelay + 0.05 * m,
      duration: 0.48 * m,
      d: GLYPHS.G,
      strokeD: STROKES.G,
      strokeWidth: 85,
    },
    {
      id: 'a',
      name: 'a',
      delay: startDelay + 0.53 * m,
      duration: 0.34 * m,
      d: GLYPHS.a,
      strokeD: STROKES.a,
      strokeWidth: 80,
    },
    {
      id: 'p',
      name: 'p',
      delay: startDelay + 0.87 * m,
      duration: 0.44 * m,
      d: GLYPHS.p,
      strokeD: STROKES.p,
      strokeWidth: 85,
    },
    {
      id: 'o1',
      name: 'o',
      delay: startDelay + 1.31 * m,
      duration: 0.3 * m,
      d: GLYPHS.o1,
      strokeD: STROKES.o1,
      strokeWidth: 80,
    },
    {
      id: 'o2',
      name: 'o',
      delay: startDelay + 1.61 * m,
      duration: 0.3 * m,
      d: GLYPHS.o2,
      strokeD: STROKES.o2,
      strokeWidth: 80,
    },
    {
      id: 'dot',
      name: '.',
      delay: startDelay + 1.93 * m,
      duration: 0.22 * m,
      d: GLYPHS.dot,
      strokeD: STROKES.dot,
      isDot: true,
    },
  ];

  const totalTime = (startDelay + 2.2 * m) * 1000;

  useEffect(() => {
    setIsCompleted(false);
    const timer = setTimeout(() => {
      setIsCompleted(true);
    }, totalTime);
    return () => clearTimeout(timer);
  }, [key, totalTime]);

  const handleReplay = () => {
    if (interactive) {
      setKey((prev) => prev + 1);
    }
  };

  return (
    <div
      key={key}
      onClick={handleReplay}
      title={interactive ? 'Click to replay handwriting animation' : undefined}
      className={`relative inline-block select-none ${
        interactive ? 'cursor-pointer group' : ''
      } ${className}`}
    >
      <svg
        viewBox="0 0 920 370"
        fill="none"
        xmlns="http://www.w3.org/2000/svg"
        className="w-full h-auto overflow-visible transition-transform duration-300 group-hover:scale-[1.01]"
        style={{ filter: 'drop-shadow(0 14px 40px rgba(0,0,0,0.45))' }}
      >
        <defs>
          {letters.map((letter) => (
            <mask
              key={`mask-${letter.id}`}
              id={`hw-mask-${uid}-${letter.id}`}
              maskUnits="userSpaceOnUse"
            >
              {letter.isDot ? (
                /* Dot ink drop reveal with authentic bounce */
                <motion.circle
                  cx="859"
                  cy="227"
                  r="30"
                  fill="white"
                  initial={{ scale: 0, opacity: 0 }}
                  animate={{ scale: 1, opacity: 1 }}
                  transition={{
                    delay: letter.delay,
                    duration: letter.duration,
                    type: 'spring',
                    stiffness: 450,
                    damping: 18,
                  }}
                />
              ) : (
                <g>
                  {/* The sequential cursive centerline pen stroke */}
                  <motion.path
                    d={letter.strokeD}
                    fill="none"
                    stroke="white"
                    strokeWidth={letter.strokeWidth || 80}
                    strokeLinecap="round"
                    strokeLinejoin="round"
                    initial={{ pathLength: 0, opacity: 0 }}
                    animate={{ pathLength: 1, opacity: 1 }}
                    transition={{
                      pathLength: {
                        delay: letter.delay,
                        duration: letter.duration,
                        ease: [0.35, 0, 0.25, 1],
                      },
                      opacity: {
                        delay: letter.delay,
                        duration: 0.04,
                      },
                    }}
                  />
                  {/* Flawless full glyph unmask safeguard once this letter completes */}
                  <motion.rect
                    x="0"
                    y="0"
                    width="920"
                    height="370"
                    fill="white"
                    initial={{ opacity: 0 }}
                    animate={{ opacity: 1 }}
                    transition={{
                      delay: letter.delay + letter.duration + 0.05,
                      duration: 0.12,
                    }}
                  />
                </g>
              )}
            </mask>
          ))}
        </defs>

        {/* Render each Apricot font letter glyph, revealed by its handwriting stroke mask */}
        {letters.map((letter) => (
          <g key={letter.id} mask={`url(#hw-mask-${uid}-${letter.id})`}>
            <motion.path
              d={letter.d}
              fill={color}
              initial={{ opacity: 0 }}
              animate={{ opacity: 1 }}
              transition={{
                delay: letter.delay,
                duration: 0.08,
              }}
            />
          </g>
        ))}
      </svg>

      {/* Subtle indicator hint on hover to replay */}
      {interactive && isCompleted && (
        <span className="absolute -bottom-5 left-1/2 -translate-x-1/2 opacity-0 group-hover:opacity-60 transition-opacity duration-300 text-[10px] tracking-widest uppercase font-mono text-amber-200/80 pointer-events-none whitespace-nowrap">
          Click to replay
        </span>
      )}
    </div>
  );
}
